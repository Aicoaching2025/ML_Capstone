"""Step 10: build model-ready feature tables for the 1-hour and 24-hour horizons.

Run from the repository root:  uv run python scripts/build_features.py
Reads data/silver (Step 8) and configs/study.yaml; writes:
  data/gold/features_h1.parquet, data/gold/features_h24.parquet
  data/gold/feature_sets.json            (columns in each feature set A, B, C)
  docs/feature_build_summary.md          (row and missing-value counts only)
Every load, observed-weather and forecast-weather input is checked with
validate_availability(). No models are fitted and no forecast errors are computed.
"""
import json
import sys
import time
import warnings
from pathlib import Path

import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
warnings.filterwarnings("ignore", message=".*generic.*unit.*", category=DeprecationWarning)
from cleaning.hours import expected_hours  # noqa: E402
from features.build import availability_frames, build_features  # noqa: E402
from features.sets import feature_columns  # noqa: E402
from validation.availability import validate_availability  # noqa: E402

STUDY = yaml.safe_load((ROOT / "configs/study.yaml").read_text())
SILVER, GOLD = ROOT / "data/silver", ROOT / "data/gold"
GOLD.mkdir(parents=True, exist_ok=True)
load = pd.read_parquet(SILVER / "nyiso/load_hourly_2017_2025.parquet")
weather = pd.read_parquet(SILVER / "noaa/weather_hourly_2017_2025.parquet")
forecast = pd.read_parquet(SILVER / "openmeteo/gfs_previous_day2_2024_2025.parquet")
p7 = pd.read_parquet(SILVER / "nyiso/p7_day_ahead_2017_2025.parquet")
targets = expected_hours(STUDY["study_start_local"], STUDY["study_end_local_exclusive"])

summary, sets_out = {}, {}
for h in STUDY["horizons_hours"]:
    print(f"Horizon {h} h: building features")
    feats, inputs = build_features(load, weather, STUDY, h, targets,
                                   forecast=forecast if h == 24 else None, p7=p7 if h == 24 else None)
    checked = {}
    for name, kind, frame in availability_frames(feats, inputs, STUDY["load_publication_delay_hours"]):
        start = time.time()
        validate_availability(frame, kind=kind)  # raises if any row uses unavailable data
        checked[name] = len(frame)
        print(f"  availability OK  {name:22s} {len(frame):6,d} rows  ({time.time() - start:.0f}s)")
    out = GOLD / f"features_h{h}.parquet"
    feats.to_parquet(out, index=False)
    print(f"  wrote {out.relative_to(ROOT)} ({len(feats):,} rows, {feats.shape[1]} columns)")
    names = ["A", "B"] + (["C_operational_h1"] if h == 1 else ["C_retrospective_h24", "C_operational_h24"])
    sets_out[f"h{h}"] = {n: feature_columns(feats, n) for n in names}
    roles = feats.split_role.value_counts().to_dict()
    nulls = {}
    for n in names:
        cols = sets_out[f"h{h}"][n]
        if n == "C_operational_h24":
            cols = [c.replace("wx_tgt_", "fc_") for c in cols]
            scope = feats.target_local_year.between(2024, 2025)
        else:
            scope = pd.Series(True, index=feats.index)
        nulls[n] = int(feats.loc[scope, cols].isna().any(axis=1).sum())
    summary[f"h{h}"] = {"rows": len(feats), "columns": feats.shape[1], "rows_by_split": roles,
                        "rows_with_any_missing_input": nulls, "availability_rows_checked": checked,
                        "target_missing": int(feats.y_load_mw.isna().sum())}
(GOLD / "feature_sets.json").write_text(json.dumps(sets_out, indent=2) + "\n")

lines = ["# Feature build summary (Step 10)", "",
         "Generated by `scripts/build_features.py`. Counts only: no models fitted, no forecast errors computed.",
         "Every load, observed-weather and forecast-weather input passed `validate_availability()` "
         f"(load delay {STUDY['load_publication_delay_hours']} h, weather delay {STUDY['weather_release_delay_minutes']} min).", ""]
for key, s in summary.items():
    lines += [f"## Horizon {key[1:]} h", "",
              f"- Rows: {s['rows']:,} target hours ({s['columns']} columns); target load missing: {s['target_missing']}",
              f"- Rows by split: {s['rows_by_split']}",
              f"- Rows with any missing input, by feature set: {s['rows_with_any_missing_input']}",
              f"- Availability checks passed: {sum(s['availability_rows_checked'].values()):,} input rows "
              f"across {len(s['availability_rows_checked'])} feature groups", ""]
lines += ["## Notes", "",
          "- C_operational_h24 counts cover 2024-2025 only; forecast weather starts 2024-01-20 12:00 UTC.",
          "- 24-hour observed target weather (wx_tgt_*) is the ideal-information reference and is not available at the origin.",
          "- NYISO P-7 (benchmark_nyiso_p7_mw) is a benchmark, never a model input."]
(ROOT / "docs/feature_build_summary.md").write_text("\n".join(lines) + "\n")
print("\n" + json.dumps(summary, indent=2))
print("\nStep 10 feature tables built.")
